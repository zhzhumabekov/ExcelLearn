def growth(r, n):
    """Множитель «сколько набегает с платежей»: ((1 + r)^n − 1) / r."""
    return n if r == 0 else ((1 + r) ** n - 1) / r


def x_pv(r, n, pmt, fv=0, typ=0):
    return -(pmt * (1 + r * typ) * growth(r, n) + fv) / (1 + r) ** n


def x_fv(r, n, pmt, pv=0, typ=0):
    return -(pv * (1 + r) ** n + pmt * (1 + r * typ) * growth(r, n))


def x_pmt(r, n, pv, fv=0, typ=0):
    return -(pv * (1 + r) ** n + fv) / ((1 + r * typ) * growth(r, n))


def schedule(r, n, principal):
    """График погашения (платёж в конце месяца): строки (остаток в начале, основной долг, проценты, остаток в конце)."""
    pay = -x_pmt(r, n, principal)
    rows, balance = [], principal
    for _ in range(n):
        interest = balance * r
        body = pay - interest
        rows.append((balance, body, interest, balance - body))
        balance -= body
    return rows


def solve(f, lo, hi):
    """Корень f на [lo, hi] делением отрезка пополам."""
    flo = f(lo)
    for _ in range(300):
        mid = (lo + hi) / 2
        if (f(mid) > 0) == (flo > 0):
            lo, flo = mid, f(mid)
        else:
            hi = mid
    return (lo + hi) / 2


def x_rate(n, pmt, pv, fv=0):
    return solve(lambda r: pv * (1 + r) ** n + pmt * growth(r, n) + fv, 1e-9, 1)


def x_nper(r, pmt, pv, fv=0):
    return solve(lambda n: pv * (1 + r) ** n + pmt * growth(r, n) + fv, 0.01, 1000)


def x_sln(cost, salvage, life):
    return (cost - salvage) / life


def x_syd(cost, salvage, life, per):
    return (cost - salvage) * (life - per + 1) / (life * (life + 1) / 2)


def x_ddb(cost, salvage, life, per, factor=2):
    book = cost
    for _ in range(per):
        dep = min(book * factor / life, max(0, book - salvage))
        book -= dep
    return dep


def th(x):
    """«2 400»: целое число с разрядами, без знака валюты."""
    return f"{round(x):,}".replace(",", " ")


def pc(x, digits=2):
    return dec(x * 100, digits) + "%"


