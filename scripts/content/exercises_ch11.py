# 2. Проценты на средний остаток
START, RATE, MONTHS = 500_000, 0.02, 12
cells = {"A1": head("Месяц"), "B1": head("На начало"), "C1": head("Проценты"), "D1": head("На конец"), "B2": kzt(START)}
balance, exp2 = START, {}
for m in range(1, MONTHS + 1):
    r = m + 1
    cells[f"A{r}"] = m
    for c in "CD" if m == 1 else "BCD":
        cells[f"{c}{r}"] = kzt()
    end = balance * (1 + RATE / 2) / (1 - RATE / 2)  # конец = начало + 2% × (начало + конец) / 2
    exp2 |= {f"C{r}": r4(end - balance), f"D{r}": r4(end)}
    balance = end
