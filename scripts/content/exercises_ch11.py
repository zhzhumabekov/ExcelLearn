# 3. Расход топлива вахтового автобуса
LEGS = [("Алматы — Конаев", 70), ("Конаев — Талдыкорган", 200), ("Талдыкорган — Уштобе", 120), ("Уштобе — Алматы", 290)]
FUEL0 = 400
cells = {
    "A1": head("Участок"),
    "B1": head("Км"),
    "C1": head("В баке в начале, л"),
    "D1": head("Средний запас, л"),
    "E1": head("Расход на 100 км"),
    "F1": head("В баке в конце, л"),
    "C2": FUEL0,
}
fuel, exp3 = FUEL0, {}
for i, (leg, km) in enumerate(LEGS, start=2):
    cells[f"A{i}"] = leg
    cells[f"B{i}"] = km
    # конец = начало − км/100 × (25 + 0,02 × (начало + конец)/2)
    end = (fuel * (1 - 0.0001 * km) - 0.25 * km) / (1 + 0.0001 * km)
    avg = (fuel + end) / 2
    exp3 |= {f"D{i}": r4(avg), f"E{i}": r4(25 + 0.02 * avg), f"F{i}": r4(end)}
    if i > 2:
        exp3[f"C{i}"] = r4(fuel)
    fuel = end
