# 1. Бонус, отчисление в фонд и КПН
PROFIT = 60_000_000
# X = прибыль − бонус; фонд = 0,05X; КПН = 0,2 × 0,95X = 0,19X; чистая = 0,76X; бонус = 0,05 × 0,76 × (P − бонус)
bonus = 0.05 * 0.76 * PROFIT / (1 + 0.05 * 0.76)
fund = 0.05 * (PROFIT - bonus)
kpn = 0.2 * (PROFIT - bonus - fund)
net = PROFIT - bonus - fund - kpn
assert abs(bonus - 0.05 * net) < 1e-6
