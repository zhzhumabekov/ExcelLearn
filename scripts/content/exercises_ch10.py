EXERCISES = []


def ex(number, eid, title, task, explain, mistake, sheet, cells_f, fills, expect):
    """cells_f: адрес → формула или (формула, формат)."""
    cells = {}
    for addr, f in cells_f.items():
        formula, fmt = f if isinstance(f, tuple) else (f, None)
        cells[addr] = {"f": formula, "fmt": fmt} if fmt else {"f": formula}
    solution = {"cells": cells}
    if fills:
        solution["fill"] = [{"source": s, "to": t} for s, t in fills]
    EXERCISES.append(
        {
            "id": eid,
            "number": number,
            "title": title,
            "task": task,
            "explain": explain,
            "mistake": mistake,
            "sheet": sheet,
            "solution": solution,
            "expect": expect,
        }
    )


def params(*rows, width=(260, 160), extra_rows=2):
    """Лист «подпись — значение» с A1; rows: (подпись, ячейка-значение) или (подпись, None) — место ответа."""
    cells = {}
    for i, (name, value) in enumerate(rows, start=1):
        cells[f"A{i}"] = label(name) if value is not None else name
        if value is not None:
            cells[f"B{i}"] = value
    return {"columns": {"A": width[0], "B": width[1]}, "rows": len(rows) + extra_rows, "cells": cells}


def sheet(file, name, base):
    return {"file": file, "name": name, **base}


