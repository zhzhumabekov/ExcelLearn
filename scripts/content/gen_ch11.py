# ---------- 11-02: весь столбец внутри столбца ----------
MONTHS = ["Январь", "Февраль", "Март", "Апрель", "Май", "Июнь"]
SALES = [4200, 3900, 4600, 5100, 4800, 5300]
NEW_MONTH, NEW_SALE = "Июль", 5500
cells = {"A1": head("Месяц"), "B1": head("Продажи, тыс. ₸"), "D1": head("Средние продажи")}
for i, (m, v) in enumerate(zip(MONTHS, SALES, strict=True), start=2):
    cells[f"A{i}"] = m
    cells[f"B{i}"] = v
cells |= {"D2": {"fmt": "number"}, "A10": label("Среднее в столбце B"), "B10": {"fmt": "number"}}
avg6 = sum(SALES) / len(SALES)
avg7 = (sum(SALES) + NEW_SALE) / (len(SALES) + 1)
