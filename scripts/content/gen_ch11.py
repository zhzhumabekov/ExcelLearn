# ---------- 11-01: благотворительность — петля и итерации ----------
INCOME, TAX, COSTS, SHARE = 15_000_000, 0.2, 10_000_000, 0.1
# Петля: c = 0,1 × после; до = доход − издержки − c; после = (1 − налог) × до → c = 0,1 × 0,8 × (5 млн − c)
donation = SHARE * (1 - TAX) * (INCOME - COSTS) / (1 + SHARE * (1 - TAX))
before_tax = INCOME - COSTS - donation
after_tax = (1 - TAX) * before_tax
assert abs(donation - SHARE * after_tax) < 1e-6
