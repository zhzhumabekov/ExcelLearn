# ---------- Независимые реализации функций Excel (для ответов) ----------


def x_trim(s):
    return " ".join(p for p in s.split(" ") if p != "")


def x_find(sub, s, start=1):
    i = s.find(sub, start - 1)
    if i < 0:
        raise ValueError("#VALUE!")
    return i + 1


def x_search(sub, s, start=1):
    i = s.lower().find(sub.lower(), start - 1)
    if i < 0:
        raise ValueError("#VALUE!")
    return i + 1


def x_mid(s, start, n):
    return s[start - 1 : start - 1 + n]


def x_value(s):
    stripped = s.strip(" ")
    if not stripped or any(not (c.isdigit() or c in ".-+") for c in stripped):
        raise ValueError("#VALUE!")
    n = float(stripped)
    return int(n) if n.is_integer() else n


def x_substitute(s, old, new, nth=None):
    if nth is None:
        return s.replace(old, new)
    idx = -1
    for _ in range(nth):
        idx = s.find(old, idx + 1)
        if idx < 0:
            return s
    return s[:idx] + new + s[idx + len(old) :]


def x_clean(s):
    return "".join(c for c in s if ord(c) >= 32)


def x_proper(s):
    out, prev_letter = [], False
    for c in s:
        if c.isalpha():
            out.append(c.lower() if prev_letter else c.upper())
            prev_letter = True
        else:
            out.append(c)
            prev_letter = False
    return "".join(out)


