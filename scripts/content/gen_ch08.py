# ---------- Числа в текстах: разряды пробелом, минус — «−», дробная часть — запятая ----------


def tg(x):
    """«277 778 ₸», «−9 722 222 ₸»: целые тенге, как в ячейке с форматом «тенге»."""
    n = round(x)
    return f"{'−' if n < 0 else ''}{abs(n):,} ₸".replace(",", " ")


def dec(x, digits=2):
    """«0,35», «1,0724»."""
    return f"{x:.{digits}f}".replace(".", ",")


def r4(x):
    return round(x, 4)


# ---------- Независимые расчёты (для ответов) ----------


def disc(v, years, rate):
    """Поток через years лет в сегодняшних деньгах."""
    return v / (1 + rate) ** years


def npv(rate, flows):
    """ЧПС Excel: первый поток — через год. Пустые (None) пропускаются вместе с годом."""
    present = [v for v in flows if v is not None]
    return sum(disc(v, i + 1, rate) for i, v in enumerate(present))


def xnpv(rate, flows, dates):
    first = dates[0]
    return sum(disc(v, (d - first).days / 365, rate) for v, d in zip(flows, dates, strict=True))


