"""Генератор вводных уроков глав 1–6 (order: 0 — первый урок главы, в оглавлении «N.0»).

Вводный урок: рабочая задача → короткая анимация главной идеи главы → «Что будет в главе» → «Что запомнить».
Ответы expect считаются здесь, на Python, независимо от движка плеера (lessons:verify сверяет их с ним).
Запуск из корня проекта: uv run python scripts/content/gen_intros.py
"""

from pathlib import Path

import yaml

ROOT = Path("content")


def head(v):
    return {"v": v, "style": "head"}


def label(v):
    return {"v": v, "style": "label"}


def kzt(v=None, style=None):
    cell = {"v": v, "fmt": "kzt"} if v is not None else {"fmt": "kzt"}
    if style:
        cell["style"] = style
    return cell


def thousands(n):
    """Разряды через неразрывный пробел: 1 050 000."""
    return f"{n:,}".replace(",", " ")


def step(title, text, say, actions):
    return {"title": title, "text": text, "say": say, "actions": actions}


def enter():
    return {"keys": ["Enter"]}


def put(addr, value):
    """Щелчок по ячейке, ввод значения и Enter."""
    return [{"click": addr}, {"type": str(value)}, enter()]


def lesson(chapter, lid, title, source, sheet, expect, steps, names=None):
    d = {"id": lid, "chapter": chapter, "order": 0, "title": title, "source": source, "sheet": sheet}
    if names:
        d["names"] = names
    d["expect"] = expect
    d["steps"] = steps
    return d


def chapter_map(items):
    return "<br>".join(f"<b>{n}</b> — {text}" for n, text in items)


