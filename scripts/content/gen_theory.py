from pathlib import Path

import yaml

ROOT = Path("content")


def head(v):
    return {"v": v, "style": "head"}


def kzt(v):
    return {"v": v, "fmt": "kzt"}


def pct(v):
    return {"v": v, "fmt": "percent"}


def thousands(n):
    """Разряды через неразрывный пробел: 1 050 000."""
    return f"{n:,}".replace(",", " ")


def p(*parts):
    return "".join(f"<p>{x}</p>" for x in parts)


def ul(*items):
    return "<ul>" + "".join(f"<li>{x}</li>" for x in items) + "</ul>"


def table(header, *rows):
    th = "".join(f"<th>{h}</th>" for h in header)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    return f"<table><tr>{th}</tr>{body}</table>"


def note(text):
    return f'<p class="note">{text}</p>'


def section(title, text, figure=None):
    d = {"title": title, "text": text}
    if figure:
        d["figure"] = figure
    return d


def figure(fid, caption, sheet, actions, expect=None, names=None):
    d = {"id": fid, "caption": caption, "sheet": sheet}
    if names:
        d["names"] = names
    d["actions"] = actions
    if expect:
        d["expect"] = expect
    return d


def put(addr, text):
    return [{"click": addr}, {"type": text}, {"keys": ["Enter"]}]


def show(addr):
    """Выделить ячейку с формулой и показать цветные рамки её ссылок."""
    return [{"click": addr}, {"showRefs": addr}]


