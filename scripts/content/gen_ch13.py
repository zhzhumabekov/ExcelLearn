ROOT = Path("content")
DAY = 86_400


def t(h, m=0, s=0):
    """Время → доля суток."""
    return (h * 3600 + m * 60 + s) / DAY


def dtv(d, h, m=0):
    """Дата и время → серийный номер с долей суток."""
    return serial(d) + t(h, m)


def cell(v, fmt):
    return {"v": v, "fmt": fmt}


def hm(x):
    """Доля суток → «8:30» (часы могут быть больше 24)."""
    total = round(x * DAY)
    return f"{total // 3600}:{total % 3600 // 60:02d}"


def r9(x):
    return round(x, 9)


def step(title, text, actions):
    return {"title": title, "text": text, "actions": actions}


def enter():
    return {"keys": ["Enter"]}


def put(addr, text):
    return [{"click": addr}, {"type": text}, enter()]


def put_fill(addr, formula, to):
    return [*put(addr, formula), {"click": addr}, {"fill": f"{addr}:{to}"}]


def format_cells(rng, *picks):
    """Выделить и Ctrl+1 → категория (и тип) → OK."""
    sel = {"dragSelect": rng} if ":" in rng else {"click": rng}
    return [sel, {"keys": ["Ctrl", "1"]}, *({"dialogPick": p} for p in picks), {"wait": 600}, {"dialogButton": "OK"}]


def lesson(order, lid, title, source, sheet, expect, steps, **extra):
    d = {"id": lid, "chapter": "ch13", "order": order, "title": title, "source": source, "sheet": sheet}
    d |= extra
    d["expect"] = expect
    d["steps"] = steps
    return d


